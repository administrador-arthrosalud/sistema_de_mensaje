CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'operador' CHECK (role IN ('admin', 'operador')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_attempts SMALLINT NOT NULL DEFAULT 0,
    locked_until TIMESTAMP(0) NULL,
    last_login_at TIMESTAMP(0) NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username ON users (LOWER(username));

ALTER TABLE reminder_messages ADD COLUMN IF NOT EXISTS sent_by_user_id BIGINT NULL;
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS sent_by_user_id BIGINT NULL;

GRANT SELECT, INSERT, UPDATE ON users TO siges_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO siges_app;
