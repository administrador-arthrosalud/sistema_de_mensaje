CREATE TABLE IF NOT EXISTS system_error_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_at TIMESTAMP(0) NOT NULL,
    component VARCHAR(32) NOT NULL,
    error_code VARCHAR(48) NOT NULL,
    http_status SMALLINT NOT NULL DEFAULT 0 CHECK (http_status BETWEEN 0 AND 599),
    occurrences INTEGER NOT NULL DEFAULT 1 CHECK (occurrences > 0),
    first_seen_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    last_seen_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    status VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent')),
    attempts SMALLINT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    sent_at TIMESTAMP(0) NULL,
    CONSTRAINT uq_system_error_alert_bucket UNIQUE (bucket_at, component, error_code, http_status)
);
CREATE INDEX IF NOT EXISTS idx_system_error_alerts_pending
    ON system_error_alerts (next_attempt_at, bucket_at) WHERE status = 'pending';
