-- Esquema local de la aplicación para PostgreSQL 12 o superior.
-- Crea primero la base (conectado como administrador a cualquier otra base):
--   CREATE DATABASE siges_dashboard ENCODING 'UTF8' TEMPLATE template0;
-- y luego ejecuta este archivo dentro de ella:
--   psql -U postgres -d siges_dashboard -f database/schema.sql
-- Nunca lo ejecutes contra la base de SIGES: SIGES es de solo lectura.

-- Búsquedas sin distinguir tildes (migración 006).
CREATE EXTENSION IF NOT EXISTS unaccent;

-- Equivale a "ON UPDATE CURRENT_TIMESTAMP" de MySQL: solo cambia updated_at
-- cuando la fila cambia de verdad.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(NEW.*) IS DISTINCT FROM ROW(OLD.*) THEN
        NEW.updated_at := LOCALTIMESTAMP(0);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key CHAR(64) NOT NULL,
    siges_cita_id BIGINT NULL,
    patient_name VARCHAR(255) NOT NULL,
    appointment_date DATE NOT NULL,
    appointment_time TIME(0) NOT NULL,
    doctor_name VARCHAR(255) NOT NULL DEFAULT '',
    specialty VARCHAR(160) NOT NULL DEFAULT '',
    sede_nombre VARCHAR(80) NULL,
    consultorio VARCHAR(160) NULL,
    modulo VARCHAR(80) NULL,
    codigo_ipress VARCHAR(8) NULL,
    appointment_note TEXT NULL,
    visit_reason TEXT NULL,
    -- Celular extraído de cita.contactos en SIGES (migración 008); NULL si no se pudo
    -- extraer uno válido. Es un punto de partida editable, no se envía sin revisión.
    destination VARCHAR(20) NULL,
    siges_programacion_id BIGINT NULL, -- programación (médico + consultorio) en SIGES, migración 013
    status VARCHAR(24) NOT NULL DEFAULT 'RESERVADO',
    created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    updated_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT uq_appointments_source_key UNIQUE (source_key),
    CONSTRAINT uq_appointments_siges_cita_id UNIQUE (siges_cita_id)
);
CREATE INDEX IF NOT EXISTS idx_appointments_pending_date ON appointments (status, appointment_date, appointment_time);
CREATE INDEX IF NOT EXISTS idx_appointments_doctor ON appointments (doctor_name);
CREATE INDEX IF NOT EXISTS idx_appointments_destination ON appointments (destination) WHERE destination IS NOT NULL;
DROP TRIGGER IF EXISTS trg_appointments_updated_at ON appointments;
CREATE TRIGGER trg_appointments_updated_at BEFORE UPDATE ON appointments
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS siges_sync_state (
    sync_key VARCHAR(64) PRIMARY KEY,
    last_cita_id BIGINT NOT NULL,
    last_run_at TIMESTAMP(0) NULL, -- latido del worker (migración 011)
    updated_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
DROP TRIGGER IF EXISTS trg_siges_sync_state_updated_at ON siges_sync_state;
CREATE TRIGGER trg_siges_sync_state_updated_at BEFORE UPDATE ON siges_sync_state
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS reminder_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    origin VARCHAR(10) NOT NULL DEFAULT 'siges' CHECK (origin IN ('siges', 'manual')),
    manual_contact_id BIGINT NULL,
    destination VARCHAR(20) NOT NULL,
    patient_name VARCHAR(255) NOT NULL,
    appointment_date DATE NOT NULL,
    appointment_time TIME(0) NOT NULL,
    doctor_name VARCHAR(255) NOT NULL DEFAULT '',
    status VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
    http_status SMALLINT NULL,
    attempted_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    sent_at TIMESTAMP(0) NULL,
    -- Quién envió (migración 010); NULL en los envíos anteriores al inicio de sesión.
    sent_by_user_id BIGINT NULL,
    -- 'no_whatsapp': Gestionalo respondió "No LID for user" (migración 014); NULL en el resto.
    failure_reason VARCHAR(20) NULL,
    -- TRUE si lo envió el worker automático de la víspera (migración 015); sent_by_user_id queda NULL.
    auto_sent BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_reminder_appointment ON reminder_messages (appointment_id, id);
CREATE INDEX IF NOT EXISTS idx_reminder_manual_contact ON reminder_messages (origin, manual_contact_id, id);
CREATE INDEX IF NOT EXISTS idx_reminder_sent_at ON reminder_messages (status, sent_at);
CREATE INDEX IF NOT EXISTS idx_reminder_destination ON reminder_messages (destination);

CREATE TABLE IF NOT EXISTS manual_contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name VARCHAR(255) NOT NULL,
    destination VARCHAR(20) NOT NULL,
    appointment_date DATE NOT NULL,
    appointment_time TIME(0) NOT NULL,
    doctor_name VARCHAR(255) NOT NULL DEFAULT '',
    -- Opcional: solo para poder probar la línea "Sede ...: dirección" del recordatorio
    -- (migración 007; el tercer valor se agregó en la 009).
    sede VARCHAR(24) NULL CHECK (sede IS NULL OR sede IN ('LIMA', 'LINCE', 'LINCE - CONSULTORIO 3')),
    created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX IF NOT EXISTS idx_manual_contact_appointment ON manual_contacts (appointment_date, appointment_time);
CREATE INDEX IF NOT EXISTS idx_manual_contact_name ON manual_contacts (patient_name);

CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination VARCHAR(20) NOT NULL,
    direction VARCHAR(10) NOT NULL CHECK (direction IN ('inbound', 'outbound')),
    body TEXT NOT NULL,
    provider_message_id VARCHAR(128) NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'received' CHECK (status IN ('received', 'pending', 'sent', 'failed')),
    http_status SMALLINT NULL,
    read_at TIMESTAMP(0) NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    sent_by_user_id BIGINT NULL, -- migración 010; solo en mensajes salientes
    -- Una restricción UNIQUE admite varios NULL, igual que en MySQL.
    CONSTRAINT uq_chat_messages_provider_id UNIQUE (provider_message_id)
);
CREATE INDEX IF NOT EXISTS idx_chat_messages_destination ON chat_messages (destination, id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_unread ON chat_messages (direction, read_at);

-- Usuarios del inicio de sesión (migración 010). Se gestionan con scripts/manage-users.php.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'operador' CHECK (role IN ('admin', 'operador')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_attempts SMALLINT NOT NULL DEFAULT 0,
    locked_until TIMESTAMP(0) NULL,
    last_login_at TIMESTAMP(0) NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username ON users (LOWER(username));

